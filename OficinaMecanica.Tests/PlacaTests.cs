using OficinaMecanica.Domain.ValueObjects;

namespace OficinaMecanica.Tests
{
    public class PlacaTests
    {
        // ??????????????????????????????????????????????
        // Formato Antigo — válidos
        // ??????????????????????????????????????????????

        [Theory]
        [InlineData("ABC-1234")]  // com hífen
        [InlineData("ABC1234")]   // sem hífen
        [InlineData("abc1234")]   // minúsculas
        [InlineData("xyz9999")]
        public void Criar_PlacaAntigaValida_DeveRetornarPlaca(string placa)
        {
            var p = Placa.Criar(placa);

            Assert.Equal(FormatoPlaca.Antigo, p.Formato);
            Assert.Equal(7, p.Valor.Length);
            Assert.DoesNotContain("-", p.Valor);
        }

        [Fact]
        public void Criar_PlacaAntiga_DeveFormatarComHifen()
        {
            var p = Placa.Criar("ABC1234");
            Assert.Equal("ABC-1234", p.Formatada);
        }

        // ??????????????????????????????????????????????
        // Formato Mercosul — válidos
        // ??????????????????????????????????????????????

        [Theory]
        [InlineData("ABC1D23")]
        [InlineData("abc1d23")]   // minúsculas
        [InlineData("XYZ9Z99")]
        [InlineData("BRA1A00")]
        public void Criar_PlacaMercosulValida_DeveRetornarPlaca(string placa)
        {
            var p = Placa.Criar(placa);

            Assert.Equal(FormatoPlaca.Mercosul, p.Formato);
            Assert.Equal(7, p.Valor.Length);
        }

        [Fact]
        public void Criar_PlacaMercosul_NaoDeveFormatarComHifen()
        {
            var p = Placa.Criar("ABC1D23");
            Assert.Equal("ABC1D23", p.Formatada);
        }

        // ??????????????????????????????????????????????
        // Normalização
        // ??????????????????????????????????????????????

        [Fact]
        public void Criar_PlacaMinuscula_DeveNormalizarParaMaiusculo()
        {
            var p = Placa.Criar("abc-1234");
            Assert.Equal("ABC1234", p.Valor);
        }

        [Fact]
        public void Criar_ComHifen_DeveRemoverHifen()
        {
            var p = Placa.Criar("ABC-1234");
            Assert.Equal("ABC1234", p.Valor);
        }

        // ??????????????????????????????????????????????
        // Inválidos
        // ??????????????????????????????????????????????

        [Theory]
        [InlineData("")]
        [InlineData("   ")]
        [InlineData("AB1234")]    // só 2 letras no início
        [InlineData("ABCD1234")]  // 4 letras no início
        [InlineData("ABC12345")]  // 5 dígitos
        [InlineData("ABC-12D4")]  // formato inválido
        [InlineData("1BC1234")]   // começa com número
        [InlineData("ABC12D3")]   // Mercosul inválido (letra na posição errada)
        public void Criar_PlacaInvalida_DeveLancarArgumentException(string placa)
        {
            Assert.Throws<ArgumentException>(() => Placa.Criar(placa));
        }

        // ??????????????????????????????????????????????
        // Igualdade (Value Object)
        // ??????????????????????????????????????????????

        [Fact]
        public void Igualdade_MesmaPlaca_DeveSerIgual()
        {
            var p1 = Placa.Criar("ABC-1234");
            var p2 = Placa.Criar("abc1234");

            Assert.Equal(p1, p2);
            Assert.True(p1 == p2);
        }

        [Fact]
        public void Igualdade_PlacasDiferentes_NaoDeveSerIgual()
        {
            var p1 = Placa.Criar("ABC1234");
            var p2 = Placa.Criar("XYZ9999");

            Assert.NotEqual(p1, p2);
            Assert.True(p1 != p2);
        }
    }
}
